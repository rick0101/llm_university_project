"""
Citation Manager - Tracks, deduplicates, and formats academic references.

Every piece of text generated by the RAG engine carries citation markers
like [1], [2], etc.  This module maps those markers to real paper metadata
and produces a formatted bibliography.
"""

import logging
import re
from dataclasses import dataclass
from typing import Optional

logger = logging.getLogger(__name__)


@dataclass
class Citation:
    """A single bibliographic reference."""

    key: int                  # numeric label  [1], [2], …
    paper_title: str
    authors: str
    year: int
    filename: str
    source_path: str = ""


class CitationManager:
    """Collects citations during generation and outputs a bibliography."""

    def __init__(self) -> None:
        self._citations: dict[str, Citation] = {}   # title → Citation
        self._next_key: int = 1

    # ── Core API ─────────────────────────────────────────────────────────

    def get_or_create_citation(self, metadata: dict) -> int:
        """
        Return the numeric key for a paper.
        Creates a new entry if first encounter.
        """
        title = metadata.get("paper_title", "Unknown")

        if title in self._citations:
            return self._citations[title].key

        citation = Citation(
            key=self._next_key,
            paper_title=title,
            authors=metadata.get("authors", "Unknown"),
            year=metadata.get("year", 0),
            filename=metadata.get("filename", ""),
            source_path=metadata.get("source_path", ""),
        )
        self._citations[title] = citation
        self._next_key += 1
        return citation.key

    def get_citation_keys_for_chunks(self, chunks: list[dict]) -> dict[str, int]:
        """Map paper titles to citation keys for a batch of chunks."""
        mapping: dict[str, int] = {}
        for chunk in chunks:
            meta = chunk.get("metadata", {})
            title = meta.get("paper_title", "Unknown")
            mapping[title] = self.get_or_create_citation(meta)
        return mapping

    # ── Formatting ───────────────────────────────────────────────────────

    def format_source_context(self, chunks: list[dict]) -> str:
        """
        Return a string ready to be injected into the LLM prompt,
        with each chunk labeled by its citation key.
        """
        parts: list[str] = []
        for chunk in chunks:
            meta = chunk.get("metadata", {})
            title = meta.get("paper_title", "Unknown")
            authors = meta.get("authors", "Unknown")
            key = self.get_or_create_citation(meta)

            parts.append(
                f"[Source {key}] — \"{title}\" by {authors}\n"
                f"{chunk['text']}"
            )
        return "\n\n---\n\n".join(parts)

    def generate_bibliography(self) -> str:
        """Produce a Markdown-formatted reference list."""
        if not self._citations:
            return ""

        lines = ["## References\n"]
        for cit in sorted(self._citations.values(), key=lambda c: c.key):
            year = str(cit.year) if cit.year else "n.d."
            lines.append(
                f"[{cit.key}] {cit.authors}. "
                f"\"{cit.paper_title}\". "
                f"({year}). "
                f"File: {cit.filename}"
            )
        return "\n\n".join(lines)

    # ── Inspection ───────────────────────────────────────────────────────

    def get_all_citations(self) -> list[Citation]:
        """All citations sorted by key."""
        return sorted(self._citations.values(), key=lambda c: c.key)

    def get_citation_count(self) -> int:
        return len(self._citations)

    def extract_used_keys(self, text: str) -> set[int]:
        """Extract all [N] citation keys from generated text."""
        return {int(m.group(1)) for m in re.finditer(r"\[(\d+)\]", text)}

    def reset(self) -> None:
        """Clear all citations (call before generating a new paper)."""
        self._citations.clear()
        self._next_key = 1
